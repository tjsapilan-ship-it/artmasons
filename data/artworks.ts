// Merge all artworks from different files
export const ARTWORKS: Artwork[] = [
  ...ARTWORKS_A_TO_M,
  ...ARTWORKS_NZ,
];

export function getArtworkSlug(artwork: Artwork | string): string {
  const name = typeof artwork === 'string' ? artwork : artwork.slug || artwork.name;
  return name
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .trim();
}

export function generateSlug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .trim();
}

export function generateArtistSlug(artist: string): string {
  return artist
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .trim();
}

export function getArtworkBySlug(slug: string): Artwork | undefined {
  return ARTWORKS.find(artwork => artwork.slug === slug);
}

export function getArtworksByArtistSlug(artistSlug: string): Artwork[] {
  return ARTWORKS.filter(artwork => generateArtistSlug(artwork.artist) === artistSlug);
}

export function getArtistNameBySlug(artistSlug: string): string | undefined {
  const artwork = ARTWORKS.find(artwork => generateArtistSlug(artwork.artist) === artistSlug);
  return artwork?.artist;
}

// Helper to enrich artwork with pricing options
export function enrichArtworkWithOptions(artwork: Artwork): Artwork {
  if (artwork.options) return artwork; // Already has options
  
  const dimensions = artwork.sellingDimensions.split('x').map(d => parseFloat(d.trim()));
  if (dimensions.length !== 2) return { ...artwork, currency: 'AED', basePrice: artwork.price };
  
  const [width, height] = dimensions;
  
  return {
    ...artwork,
    currency: 'AED',
    basePrice: artwork.price,
    options: [
      { 
        id: 'opt1', 
        width, 
        height, 
        price: artwork.price, 
        label: 'Original Size' 
      }
    ]
  };
}
